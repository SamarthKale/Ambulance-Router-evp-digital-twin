"""One base signal program per demand level, tuned with SUMO's tlsCycleAdaptation.py (Webster),
shared by every arm so OFF is not a strawman (CLAUDE.md section 14).

The tool counts <vehicle> elements, while the scenarios' demand is Poisson <flow>s, so one
hour of the demand is first expanded into vehicles with SUMO's --vehroute-output. The phase
states, yellows (4 s) and all-reds (2 s) stay as built; only the greens change. The live demo
keeps the net's own program.
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

from simulation.sumo import SCENARIOS_DIR, find_sumo_binary

TUNING_SEED = 42  # the demand sample the program is tuned on (the scenario's own seed)
PROGRAM_ID = "tuned"
YELLOW_S = 4
ALL_RED_PER_CYCLE_S = 4  # 2 s after each of the two greens


def program_path(out: Path, scenario: str, scale: float) -> Path:
    return out / "programs" / f"{scenario}_x{scale:g}.add.xml"


def tuned_program(scenario: str, scale: float, out: Path) -> Path:
    """The tuned program file for this demand (generated once, then reused)."""
    path = program_path(out, scenario, scale)
    if path.exists():
        return path
    path.parent.mkdir(parents=True, exist_ok=True)
    sumo = find_sumo_binary()
    tool = sumo.parent.parent / "tools" / "tlsCycleAdaptation.py"
    folder = SCENARIOS_DIR / scenario
    with tempfile.TemporaryDirectory(prefix="ef_tune_") as tmp:
        vehicles = Path(tmp) / "vehicles.xml"
        subprocess.run(
            [str(sumo), "-c", str(folder / "simulation.sumocfg"), "--scale", f"{scale:g}",
             "--seed", str(TUNING_SEED), "--end", "3600", "--vehroute-output", str(vehicles),
             "--no-warnings", "true", "--no-step-log", "true"],
            check=True, capture_output=True,
        )  # fmt: skip
        _flatten_routes(vehicles)
        env = {**os.environ, "SUMO_HOME": str(sumo.parent.parent)}
        subprocess.run(
            [sys.executable, str(tool), "-n", str(folder / "network.net.xml"),
             "-r", str(vehicles), "-b", "0", "-y", str(YELLOW_S), "-a", str(ALL_RED_PER_CYCLE_S),
             "-p", PROGRAM_ID, "-o", str(path)],
            check=True, capture_output=True, env=env,
        )  # fmt: skip
    _replace_header(path, scenario, scale)
    return path


def _replace_header(path: Path, scenario: str, scale: float) -> None:
    """The tool's header comment holds its command line: local paths, and '--' (from paths
    such as 'c--sparkathon26'), which XML forbids in comments. Keep a short one instead."""
    text = re.sub(r"<!--.*?-->", "", path.read_text(encoding="utf-8"), count=1, flags=re.S)
    note = (
        f"<!-- {scenario} at demand x{scale:g}: tuned by SUMO's tlsCycleAdaptation.py on one hour "
        f"of demand (seed {TUNING_SEED}), yellow {YELLOW_S} s, all-red "
        f"{ALL_RED_PER_CYCLE_S} s per cycle. Generated by evaluation/programs.py. -->"
    )
    declaration, _, body = text.partition("?>")
    path.write_text("\n".join((f"{declaration}?>", note, body.lstrip())), encoding="utf-8")


def _flatten_routes(vehicles: Path) -> None:
    """A vehicle SUMO rerouted (heavy demand) is written with a routeDistribution, which the
    tool can't read: keep the route it ended up driving."""
    tree = ET.parse(vehicles)
    for vehicle in tree.getroot().iter("vehicle"):
        distribution = vehicle.find("routeDistribution")
        if distribution is not None:
            routes = distribution.findall("route")
            vehicle.remove(distribution)
            if routes:
                vehicle.append(ET.Element("route", {"edges": routes[-1].get("edges", "")}))
    tree.write(vehicles, encoding="unicode")


def cycle_summary(path: Path) -> dict[str, dict[str, float]]:
    """Per signal: cycle length and green times (for the report)."""
    out = {}
    for logic in ET.parse(path).getroot().iter("tlLogic"):
        durations = [(p.get("state", ""), float(p.get("duration", 0))) for p in logic.iter("phase")]
        greens = [d for s, d in durations if "G" in s or "g" in s]
        out[logic.get("id", "")] = {"cycle_s": sum(d for _, d in durations), "greens_s": greens}
    return out
